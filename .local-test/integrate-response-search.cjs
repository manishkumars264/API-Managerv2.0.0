const fs = require('node:fs');
const file = 'src/App.tsx';
let source = fs.readFileSync(file, 'utf8');
const anchor = "<div className=\"toolbar-spacer\" /><button className={`icon-button ${wrap ? 'enabled' : ''}`} title=\"Toggle word wrap\"";
const replacement = "<div className=\"toolbar-spacer\" /><button className=\"icon-button\" title=\"Search response (Ctrl+F)\" aria-label=\"Search response body\" onClick={() => { if (responseMode === 'Preview') patchTab({ responseTab: 'Body:Raw' }); setResponseFindRequested(true); }}><Search size={16} /></button><button className={`icon-button ${wrap ? 'enabled' : ''}`} title=\"Toggle word wrap\"";
if (source.split(anchor).length !== 2) throw new Error('Response toolbar anchor must be unique.');
source = source.replace(anchor, replacement);
const editorAnchor = '<CodeEditor editorKey={`${current.id}:response:${responseMode}`}';
if (source.split(editorAnchor).length !== 2) throw new Error('Response editor anchor must be unique.');
source = source.replace(editorAnchor, '<CodeEditor editorRef={responseEditorRef} editorKey={`${current.id}:response:${responseMode}`}');
fs.writeFileSync(file, source);
